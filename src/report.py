"""Results that go into the paper: numbers (LaTeX macros), tables and the figure style.

Every script in run/ ends by calling `save_results(name, values)`, which writes

    data/results/<name>.json          machine-readable copy of every number
    paper/generated/res_<name>.tex    one line per number:  \\setres{key}{value}

main.tex reads the generated files, so a sentence such as
"balanced accuracy of \\res{brf-balacc}" always shows the value of the last run; a number that has
not been produced yet appears in red as [key?]. Tables are written to paper/generated/tab_*.tex.
"""
import json
import math

import matplotlib as mpl
import numpy as np

from paths import DATA, ROOT

GEN_DIR = ROOT / "paper" / "generated"
RES_DIR = DATA / "results"


def _ensure():
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    RES_DIR.mkdir(parents=True, exist_ok=True)


def _json_ready(v):
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        return float(v)
    if isinstance(v, np.ndarray):
        return v.tolist()
    if isinstance(v, dict):
        return {str(k): _json_ready(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [_json_ready(x) for x in v]
    return v


def save_results(name, latex_values, raw=None):
    """Write paper/generated/res_<name>.tex (LaTeX-ready strings) and data/results/<name>.json."""
    _ensure()
    lines = [f"% generated by run/ -- do not edit by hand (results '{name}')"]
    for k, v in latex_values.items():
        lines.append(f"\\setres{{{str(k).replace('_', '-')}}}{{{v}}}")   # keys: letters, digits, '-'
    (GEN_DIR / f"res_{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    payload = {"latex": latex_values, "raw": _json_ready(raw or {})}
    (RES_DIR / f"{name}.json").write_text(json.dumps(payload, indent=2, ensure_ascii=False),
                                          encoding="utf-8")


def save_table(name, tex):
    _ensure()
    (GEN_DIR / f"{name}.tex").write_text(
        f"% generated by run/ -- do not edit by hand\n{tex}\n", encoding="utf-8")


# ---------------------------------------------------------------- number formatting
def f2(x):
    return f"{x:.2f}"


def f3(x):
    return f"{x:.3f}"


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}\\%"


def p_fmt(p, n_perm=None):
    """p-value for tables; with a permutation count the smallest value is 1/(n_perm+1)."""
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if n_perm is not None and p <= 1.0 / (n_perm + 1) + 1e-12:
        return f"$\\leq${1.0 / (n_perm + 1):.1g}"
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def p_txt(p, n_perm=None):
    """p-value for running text, with its relation: '= 0.032', '$\\leq$ 0.005', '$<$ 0.001'.

    Use it in main.tex after the symbol:  $p$~\\res{key}.
    """
    s = p_fmt(p, n_perm)
    if s == "--":
        return s
    if s.startswith("$"):
        rel, num = s.split("$")[1], s.split("$")[2]
        return f"${rel}$ {num}"
    return f"= {s}"


def ci_fmt(m, lo, hi, fmt=f2):
    return f"{fmt(m)} [{fmt(lo)}, {fmt(hi)}]"


def italic_species(name):
    return f"\\textit{{{name}}}"


# ---------------------------------------------------------------- figure style
def set_style():
    mpl.rcParams.update({
        "font.size": 8, "axes.titlesize": 8, "axes.labelsize": 8, "legend.fontsize": 7,
        "xtick.labelsize": 7, "ytick.labelsize": 7, "axes.spines.top": False,
        "axes.spines.right": False, "axes.linewidth": 0.6, "xtick.major.width": 0.6,
        "ytick.major.width": 0.6, "pdf.fonttype": 42, "figure.dpi": 150,
    })


def panel_label(ax, letter):
    ax.text(-0.12, 1.04, letter, transform=ax.transAxes, fontsize=9, fontweight="bold",
            va="bottom", ha="left")
